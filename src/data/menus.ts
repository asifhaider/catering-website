function svgPlaceholder(category: 'protein' | 'vegetarian' | 'side', label: string): string {
  const bg = category === 'protein' ? '#D97706' : category === 'vegetarian' ? '#4D7C0F' : '#78716C';
  const fg = '#FFFFFF';
  const emoji = category === 'protein' ? '🍖' : category === 'vegetarian' ? '🥦' : '🍚';
  const encoded = encodeURIComponent(
    `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300" viewBox="0 0 400 300">
      <rect width="400" height="300" fill="${bg}"/>
      <text x="200" y="130" text-anchor="middle" font-size="64" font-family="sans-serif">${emoji}</text>
      <text x="200" y="185" text-anchor="middle" font-size="18" font-family="sans-serif" fill="${fg}" font-weight="bold">${label}</text>
    </svg>`
  );
  return `data:image/svg+xml,${encoded}`;
}

