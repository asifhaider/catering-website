export function getMenuForDate(dateStr) {
  const date = new Date(dateStr + "T12:00:00");
  const day = date.getDay();
  return MENUS[day];
}

export function isDateValid(dateStr) {
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const selected = new Date(dateStr + "T12:00:00");
  const minDate = new Date(today);
  minDate.setDate(today.getDate() + MIN_DAYS_AHEAD);
  const maxDate = new Date(today);
  maxDate.setDate(today.getDate() + MAX_DAYS_AHEAD);
  return selected >= minDate && selected <= maxDate;
}

export function getMinDate() {
  const d = new Date();
  d.setDate(d.getDate() + MIN_DAYS_AHEAD);
  return d.toISOString().split("T")[0];
}

export function getMaxDate() {
  const d = new Date();
  d.setDate(d.getDate() + MAX_DAYS_AHEAD);
  return d.toISOString().split("T")[0];
}

export function formatDate(dateStr) {
  const d = new Date(dateStr + "T12:00:00");
  return d.toLocaleDateString("en-US", { weekday: "long", year: "numeric", month: "long", day: "numeric" });
}

export function generateOrderId() {
  return "MK-" + Date.now().toString(36).toUpperCase();
}
