export const WEEKLY_MENU: DayMenu[] = [
  { dayOfWeek: 0, items: sunday },
  { dayOfWeek: 1, items: monday },
  { dayOfWeek: 2, items: tuesday },
  { dayOfWeek: 3, items: wednesday },
  { dayOfWeek: 4, items: thursday },
  { dayOfWeek: 5, items: friday },
  { dayOfWeek: 6, items: saturday },
]

export function getMenuForDayOfWeek(dayOfWeek: DayOfWeek): DayMenu {
  const menu = WEEKLY_MENU.find((m) => m.dayOfWeek === dayOfWeek)
  if (!menu) {
    throw new Error(`No menu configured for day of week ${dayOfWeek}`)
  }
  return menu
}

export function getMenuForDate(date: Date): DayMenu {
  return getMenuForDayOfWeek(date.getDay() as DayOfWeek)
}

export function findFoodItemById(id: string): FoodItem | undefined {
  return WEEKLY_MENU.flatMap((m) => m.items).find((item) => item.id === id)
}
