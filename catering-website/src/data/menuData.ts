let counter = 0
/** Deterministic small jitter so items in the same category aren't nutritionally identical. */
function jitter(base: number, spread: number): number {
  counter += 1
  const pseudoRandom = Math.sin(counter * 12.9898) * 43758.5453
  const fraction = pseudoRandom - Math.floor(pseudoRandom)
  return Math.round(base + (fraction - 0.5) * 2 * spread)
}

interface ItemInput {
  id: string
  name: string
  category: FoodCategory
  price: number
  description: string
  ingredients: string[]
  allergens: string[]
  nutritionOverride?: Partial<NutritionFacts>
}

function food(input: ItemInput): FoodItem {
  const base = NUTRITION_BASELINE[input.category]
  const nutrition: NutritionFacts = {
    ...base,
    calories: jitter(base.calories, 40),
    totalFatGrams: jitter(base.totalFatGrams, 4),
    saturatedFatGrams: jitter(base.saturatedFatGrams, 2),
    cholesterolMg: jitter(base.cholesterolMg, 15),
    sodiumMg: jitter(base.sodiumMg, 80),
    totalCarbsGrams: jitter(base.totalCarbsGrams, 6),
    dietaryFiberGrams: jitter(base.dietaryFiberGrams, 1),
    sugarsGrams: jitter(base.sugarsGrams, 2),
    proteinGrams: jitter(base.proteinGrams, 4),
    ...input.nutritionOverride,
  }
  return {
    id: input.id,
    name: input.name,
    category: input.category,
    pricePerPortion: input.price,
    imageUrl: `https://picsum.photos/seed/${input.id}/480/360`,
    description: input.description,
    ingredients: input.ingredients,
    nutrition,
    allergens: input.allergens,
  }
}

